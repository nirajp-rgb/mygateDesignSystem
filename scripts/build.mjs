// Build CSS variables and flat JSON from the token files.
//   npm run build   → writes dist/
//   npm run check   → validates only (no files written); exits 1 on errors
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadTheme, resolve, singleRef, cssName, cssValue, contrast, writeJSON } from './lib.mjs';

const CHECK_ONLY = process.argv.includes('--check');
const errors = [], warnings = [];
const out = {};

for (const id of ['light', 'dark']) {
  const map = loadTheme(id);
  const vars = new Map(), flat = {};
  for (const [key, { path, token, set, source }] of map) {
    const { value, errors: errs } = resolve(token.$value, map);
    errs.forEach((e) => errors.push(`[${id}] ${path.join('/')}: ${e}`));
    flat[path.join('/')] = value;
    const name = cssName(path);
    if (vars.has(name) && vars.get(name).set !== set) errors.push(`[${id}] two tokens map to ${name}`);
    // Semantic and layout tokens that are a plain alias point at the primitive's variable, so the CSS mirrors Figma.
    const ref = singleRef(token.$value);
    const css = ref && map.get(ref)?.source ? `var(${cssName(map.get(ref).path)})` : cssValue(token.$type, value);
    vars.set(name, { css, set, source });
  }
  out[id] = { vars, flat };
}

// Contrast check on the pairs the docs site checks
const pairs = JSON.parse(readFileSync(join(ROOT, 'scripts', 'contrast-pairs.json'), 'utf8'));
const byCss = (id) => Object.fromEntries(Object.entries(out[id].flat).map(([p, v]) => [cssName(p.split('/')), v]));
for (const id of ['light', 'dark']) {
  const vals = byCss(id);
  for (const [fg, bg, label, need] of pairs) {
    const a = vals[fg], b = vals[bg];
    if (!a || !b) { errors.push(`[${id}] contrast pair "${label}" uses a token that does not exist`); continue; }
    const r = contrast(a.slice(0, 7), b.slice(0, 7));
    if (r < need) warnings.push(`[${id}] ${label}: ${r.toFixed(2)}:1 (needs ${need}:1) — ${fg} on ${bg}`);
  }
}

warnings.forEach((w) => console.warn('warn  ' + w));
errors.forEach((e) => console.error('error ' + e));
if (errors.length) { console.error(`\n${errors.length} error(s). Nothing written.`); process.exit(1); }
if (CHECK_ONLY) { console.log(`Tokens OK. ${warnings.length} contrast warning(s).`); process.exit(0); }

// dist/tokens.css: primitives + layout + light semantic on :root; dark semantic under [data-theme="dark"] and prefers-color-scheme
const line = ([n, v]) => `  ${n}: ${v.css};`;
const light = [...out.light.vars];
const darkOnly = [...out.dark.vars].filter(([n, v]) => v.set.startsWith('semantic'));
const css = `/* Generated by scripts/build.mjs from tokens/. Do not edit by hand. */\n:root {\n${light.map(line).join('\n')}\n}\n\n[data-theme="dark"] {\n${darkOnly.map(line).join('\n')}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${darkOnly.map((e) => '  ' + line(e)).join('\n')}\n  }\n}\n`;
const dist = join(ROOT, 'dist');
mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, 'tokens.css'), css);
writeJSON(join(dist, 'tokens.light.json'), out.light.flat);
writeJSON(join(dist, 'tokens.dark.json'), out.dark.flat);
console.log(`Built dist/tokens.css (${light.length} variables, ${darkOnly.length} dark overrides), tokens.light.json, tokens.dark.json. ${warnings.length} contrast warning(s).`);
